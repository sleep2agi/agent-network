#!/usr/bin/env node
/**
 * Build the standalone `anet` executable from un-obfuscated TypeScript.
 *
 *   node scripts/build-anet-bin.mjs --target bun-linux-x64 --outfile dist/anet-linux-x64
 *
 * Rewrites `agent-network/src/standalone-build-stamp.ts` for the compile,
 * then restores the committed inactive stamp. Does not publish.
 *
 * claude-agent-sdk, the Codex SDK, and node-pty stay external (native,
 * platform-specific, on-demand). The Hub and agent-node entry points are
 * bundled. The npm obfuscated bundle is not an input.
 */
import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync, mkdtempSync, rmSync, statSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const stampPath = join(repoRoot, "agent-network", "src", "standalone-build-stamp.ts");

function arg(name) {
  const i = process.argv.indexOf(name);
  if (i === -1 || !process.argv[i + 1]) {
    console.error(`build-anet-bin: missing ${name}`);
    process.exit(2);
  }
  return process.argv[i + 1];
}

function readVersion(pkgDir) {
  const pkg = JSON.parse(readFileSync(join(repoRoot, pkgDir, "package.json"), "utf8"));
  if (typeof pkg.version !== "string" || !pkg.version) {
    console.error(`build-anet-bin: ${pkgDir}/package.json has no version`);
    process.exit(2);
  }
  return pkg.version;
}

function run(cmd, args) {
  const result = spawnSync(cmd, args, { cwd: repoRoot, stdio: "inherit" });
  if (result.status !== 0) {
    process.exit(result.status ?? 1);
  }
}

const target = arg("--target");
const outfile = resolve(repoRoot, arg("--outfile"));
const bundleFlag = process.argv.indexOf("--bundle-version");
const bundleVersion = bundleFlag === -1 ? readVersion("agent-network") : process.argv[bundleFlag + 1];
if (!bundleVersion) {
  console.error("build-anet-bin: empty --bundle-version");
  process.exit(2);
}
const metaFlag = process.argv.indexOf("--meta");
const metaPath = metaFlag === -1 ? `${outfile}.build.json` : resolve(repoRoot, process.argv[metaFlag + 1]);

const versions = {
  anet: readVersion("agent-network"),
  agentNode: readVersion("agent-node"),
  commhubServer: readVersion("server"),
  bundle: bundleVersion,
};

const originalStamp = readFileSync(stampPath, "utf8");
const temp = mkdtempSync(join(tmpdir(), "anet-bin-"));
const nodeServerOut = join(temp, "node-server.js");

function restore() {
  writeFileSync(stampPath, originalStamp);
}

try {
  run("bun", [
    "build",
    "agent-network/src/node-server.ts",
    "--target", "node",
    "--minify",
    "--outfile", nodeServerOut,
  ]);
  run(process.execPath, ["agent-network/scripts/stamp-node-server-version.mjs", nodeServerOut]);
  const nodeServerJs = readFileSync(nodeServerOut, "utf8");
  const stamp = {
    standalone: true,
    versions,
    nodeServerJs,
  };
  const generated = `/**
 * GENERATED by scripts/build-anet-bin.mjs for one \`bun build --compile\`.
 * Restored to the inactive committed stamp when the build script exits.
 * Do not commit this file while \`standalone\` is true.
 */
export interface StandalonePackageVersions {
  anet: string;
  agentNode: string;
  commhubServer: string;
  bundle: string;
}
export interface StandaloneBuildStamp {
  standalone: boolean;
  versions: StandalonePackageVersions | null;
  nodeServerJs: string | null;
}
export const STANDALONE_BUILD_STAMP: StandaloneBuildStamp = ${JSON.stringify(stamp, null, 2)};
`;
  writeFileSync(stampPath, generated);

  run("bun", [
    "build",
    "--compile",
    "--minify",
    `--target=${target}`,
    "--external", "@anthropic-ai/claude-agent-sdk",
    "--external", "@anthropic-ai/claude-agent-sdk-*",
    "--external", "@openai/codex-sdk",
    "--external", "@openai/codex",
    "--external", "node-pty",
    "agent-network/bin/anet-bin.ts",
    "--outfile", outfile,
  ]);
} finally {
  restore();
  rmSync(temp, { recursive: true, force: true });
}

const size = statSync(outfile).size;
const meta = { ...versions, target, outfile, bytes: size };
writeFileSync(metaPath, `${JSON.stringify(meta, null, 2)}\n`);
console.log(`built ${outfile} (${size} bytes)`);
console.log(`meta ${metaPath}`);
