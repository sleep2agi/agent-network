'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const os=require('node:os');
const {spawnSync}=require('node:child_process');
const root=fs.mkdtempSync(path.join(os.tmpdir(),'large-history-launcher-'));
const nodeDir=path.join(root,'.anet/nodes/stable-id');
const bin=path.join(root,'bin');fs.mkdirSync(nodeDir,{recursive:true});fs.mkdirSync(bin);
fs.writeFileSync(path.join(nodeDir,'config.json'),JSON.stringify({node_name:'node-with-alias',node_id:'stable-id',channels:['server:commhub']}));
const codex=path.join(bin,'codex-actual');
fs.writeFileSync(codex,'#!/bin/sh\nprintf "%s\\n" "$@"\n',{mode:0o755});
fs.writeFileSync(path.join(bin,'anet'),`#!/usr/bin/env node
const child=require('node:child_process');
const timer=setTimeout(()=>{},15000);console.log('timer='+timer._idleTimeout);clearTimeout(timer);
console.log('preloadInherited='+Boolean(process.env.NODE_OPTIONS));
const env={...process.env};delete env.NODE_OPTIONS;
const c=child.spawnSync(process.execPath,['-e','const t=setTimeout(()=>{},15000);console.log(t._idleTimeout);clearTimeout(t)'],{env,encoding:'utf8'});
console.log('childTimer='+c.stdout.trim());
`,{mode:0o755});
const env={...process.env,PATH:bin+':'+process.env.PATH,ANET_CODEX_ACTUAL_BIN:codex,ANET_CODEX_TUI_PROXY_PORT:'24709'};
const launch=spawnSync('bash',['deploy/codex-large-history/start-node.sh',root,'node-with-alias'],{env,encoding:'utf8'});
assert.equal(launch.status,0,launch.stderr);
assert.match(launch.stdout,/timer=120000/);assert.match(launch.stdout,/preloadInherited=false/);assert.match(launch.stdout,/childTimer=15000/);
const setting=path.join(nodeDir,'large-history-start.json');
assert.deepEqual(JSON.parse(fs.readFileSync(setting)),{codexBin:codex,proxyPort:24709});
assert.equal(fs.statSync(setting).mode&0o777,0o600);
const isolated={...process.env,CODEX_HOME:path.join(nodeDir,'codex-home')};
delete isolated.ANET_CODEX_ACTUAL_BIN;delete isolated.ANET_CODEX_TUI_PROXY_PORT;
fs.mkdirSync(isolated.CODEX_HOME);
const shim=spawnSync('bash',['deploy/codex-large-history/codex-shim.sh','app-server','--listen','ws://127.0.0.1:24700'],{env:isolated,encoding:'utf8'});
assert.equal(shim.status,0,shim.stderr);assert.match(shim.stdout,/app-server\n--listen\nws:\/\/127.0.0.1:24700/);
const tui=spawnSync('bash',['deploy/codex-large-history/codex-shim.sh','resume','--remote','ws://127.0.0.1:24700','thread-test'],{env:isolated,encoding:'utf8',timeout:15000});
assert.equal(tui.status,0,tui.stderr);assert.match(tui.stdout,/ws:\/\/127.0.0.1:24709\nthread-test/);
console.log('PASS launcher: alias resolution, mode-600 settings, tmux environment isolation, 120s launch deadline, normal child timers, correct upstream/TUI endpoints');
