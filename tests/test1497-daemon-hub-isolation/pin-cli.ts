mkdirSync("/tmp/cli241", { recursive: true });
await Bun.write("/tmp/cli241/cli.tgz", bytes);
execFileSync("tar", ["-xzf", "/tmp/cli241/cli.tgz", "-C", "/tmp/cli241"], { timeout: 10_000 });
cpSync("/tmp/cli241/package/dist", "agent-network/dist", { recursive: true });
console.log("Verified published CLI .241 sha256=887fb13e; source runtime sibling retained");
