// 排队可见性 —— 「你连发三条，第二三条去哪儿了」。
//
// 现状（2026-11-03 之前）：入站是**串行**的（agent-node 的 thinkQueue 是 process-wide
// 的 promise 链，一次只跑一轮），所以第二条会等第一条跑完。但用户看不到这件事：
// 他只会看到第一条的「⏳ 处理中…」，然后第二三条**长时间没有任何回音**。
// 对发消息的人来说，"排队"和"卡死"长得一模一样。
//
// 所以这里补的不是队列本身（队列已经有了），而是**队列的可见性**：
// 当自己前面已经有人在排队时，立刻回一句"你在第几位"。
//
// 三条边界：
//   ① 只在**确实有积压**时发（ahead ≥ 1），否则每句话都多一条噪声；
//   ② 不发"预计还要多久"——那个数字没有人能算准，给了就是编；
//   ③ 文案要能让用户决定"等还是重发"，所以要说清前面几条。

/** 前面还有 ahead 条时的那句话；ahead ≤ 0 返回空串（不发）。 */
export function queueNoticeText(ahead: number): string {
  if (!Number.isFinite(ahead) || ahead < 1) return "";
  const n = Math.floor(ahead);
  return `⏳ 已排队：前面还有 ${n} 条在处理，轮到这条会立刻开始（可以继续发，不会丢）。`;
}
